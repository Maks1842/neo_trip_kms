"""Генерация идентификаторов.

UUIDv7 выбран вместо UUIDv4 ради локальности вставки в B-tree: первые 48 бит —
метка времени, поэтому новые записи ложатся в конец индекса, а не размазываются по нему.

В Python 3.13 в стандартной библиотеке нет uuid.uuid7() (появляется в 3.14), поэтому
используется внешняя библиотека. Это единственное место в проекте, которое о ней знает —
переход на stdlib будет заменой одной строки.
"""

from uuid import UUID

import uuid_utils


def uuid7() -> UUID:
    """Новый UUID версии 7."""
    # uuid_utils возвращает собственный тип, приводим к стандартному uuid.UUID,
    # иначе SQLAlchemy и Pydantic будут работать с ним некорректно.
    return UUID(str(uuid_utils.uuid7()))
